def render_site(data: dict) -> str:
    blob = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")
    page = SITE_TEMPLATE
    if list(data.get("status_labels") or []) == list(_schema.STATUSES):
        for old, new in _SITE_V2:
            page = page.replace(old, new)
    return page.replace("__KB_DATA__", blob)


