    path = kb.root / object_path(kb.root, eid, v2kind)
    if path.exists():
        print(f"new: {path} already exists", file=sys.stderr)
        return 1
    path.parent.mkdir(parents=True, exist_ok=True)
    make = skeleton_v2 if kb_is_v2(kb) else skeleton
    path.write_text(make(eid, args.kind or "draft", args.title or "", is_assumption),
                    encoding="utf-8", newline="\n")
    print(path.relative_to(kb.root).as_posix())
    return 0


