DIRECTION_SECTIONS = ("Questions", "Candidate claims", "Falsifiers", "Next steps")
_ITEM_RE = re.compile(r"^\s*[-*]\s+`?(?:([a-z0-9]+):)?([A-Za-z][^\s`,;:—]*)`?")


def direction_items(kb, e) -> list:
    """``[(section, ref, resolved id or None)]`` of a direction's bullet lists (the
    format ``notebook.py direction`` reads: ``- s1:<id> — text``); HTML comments skipped."""
    out, section, in_comment = [], None, False
    for ln in e.body.split("\n"):
        s = ln.strip()
        if in_comment:
            in_comment = "-->" not in s
            continue
        if s.startswith("<!--"):
            in_comment = "-->" not in s
            continue
        if s.startswith("## "):
            section = s[3:].strip()
            continue
        if section not in DIRECTION_SECTIONS:
            continue
        m = _ITEM_RE.match(ln)
        if not m:
            continue
        ns, ref = m.groups()
        if ns and ns != (kb.rules.ns or _workspace.repo_ns(kb.root)):
            out.append((section, f"{ns}:{ref}", None))
        else:
            out.append((section, ref, lookup(kb, ref)[0]))
    return out


def _vlink(e) -> str:
    return md_link(e.id, rel_from(VIEWS_DIR, e.path))


def _objects(kb):
    return [e for e in kb.sorted() if e.etype not in LEDGER_TYPES]


def view_objects(kb) -> str:
    out = [GENERATED, "# Objects by kind", "",
           "One table per folder of `objects/`. Generated by `registry.py build`; the "
           "files are the source of truth.", ""]
    for kind in OBJECT_FOLDERS:
        ents = [e for e in _objects(kb) if e.folder == kind]
        out += [f"## {kind} ({len(ents)})", ""]
        if not ents:
            out += ["_(none)_", ""]
            continue
        out += ["| id | status | summary |", "|---|---|---|"]
        for e in ents:
            out.append(f"| {_vlink(e)} | {cell(status_cell(e))} | {cell(summary_of(e))} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def _unsettled(e) -> bool:
    st = e.meta.get("status")
    return e.etype == "claim" and (st in ("Not settled",) + _schema.UNSETTLED) and \
        (e.v2 is None or (e.v2.get("lifecycle") or "active") == "active")


def view_directions(kb) -> str:
    out = [GENERATED, "# Open questions by direction", "",
           "Each research direction (`objects/direction/`) with the status of every "
           "question and candidate claim it lists, then the unsettled questions that no "
           "direction lists yet. Generated by `registry.py build`.", ""]
    listed = set()
    for d in kb.sorted({"direction"}):
        items = direction_items(kb, d)
        out += [f"## {_vlink(d)} — {cell(d.meta.get('title', ''))}", ""]
        if summary_of(d) and summary_of(d) != d.meta.get("title"):
            out += [summary_of(d), ""]
        for sec in ("Questions", "Candidate claims"):
            rows = [(r, rid) for s, r, rid in items if s == sec]
            out += [f"### {sec} ({len(rows)})", ""]
            if not rows:
                out += ["_(none)_", ""]
                continue
            out += ["| item | status | summary |", "|---|---|---|"]
            for ref, rid in rows:
                if rid is None:
                    out.append(f"| {cell(ref)} | (no object here) | |")
                    continue
                listed.add(rid)
                e = kb.entities[rid]
                out.append(f"| {_vlink(e)} | {cell(status_cell(e))} | {cell(summary_of(e))} |")
            out.append("")
        nf = sum(1 for s, _, _ in items if s == "Falsifiers")
        out += [f"Falsifiers recorded: {nf}.", ""]
    rest = [e for e in kb.sorted({"claim"}) if _unsettled(e) and e.id not in listed
            and e.meta.get("kind") in ("question", "open", "conj")]
    out += ["## Unsettled questions and conjectures in no direction", ""]
    out += [f"- {_vlink(e)} — {status_cell(e)} — {summary_of(e)}" for e in rest] or ["_(none)_"]
    return "\n".join(out) + "\n"


_CLASS_STYLE = {"true": "fill:#dcf1e2", "true-modulo": "fill:#e6f1d5",
                "false": "fill:#f9dedb", "unsettled": "fill:#e9e9ee"}


def _class_of(e):
    if e.v2 is not None:
        return _schema.project(e.v2) if e.etype == "claim" else _projection.NA
    st = e.meta.get("status")
    return _projection.project(st, _projection.S1) if isinstance(st, str) else _projection.NA


def view_graph(kb) -> str:
    edges = []
    for e in _objects(kb):
        for key in ("depends_on",):
            for d in resolved_list(kb, e, key):
                if kb.entities[d].etype not in LEDGER_TYPES:
                    edges.append((e.id, d, "depends_on"))
        if e.v2 is not None:
            for ref in e.v2.get("modulo") or []:
                rid = lookup(kb, ref)[0] if isinstance(ref, str) else None
                if rid:
                    edges.append((e.id, rid, "modulo"))
    ids = sorted({x for s, t, _ in edges for x in (s, t)},
                 key=lambda i: kb.sort_key(kb.entities[i]))
    node = {i: f"n{k}" for k, i in enumerate(ids)}
    out = [GENERATED, "# Dependency graph", "",
           "An arrow X → Y means X `depends_on` Y; a dotted arrow, that Y is one of X's "
           "`modulo` inputs. Fill: green proved, light green proved-modulo, red refuted, "
           "grey unsettled; no fill, no status. Objects with no edge are left out. "
           "Generated by `registry.py build`.", "",
           f"{len(ids)} objects, {len(edges)} edges.", "", "```mermaid", "graph LR"]
    for i in ids:
        out.append(f'  {node[i]}["{i}"]')
    for s, t, k in edges:
        out.append(f"  {node[s]} {'-.->' if k == 'modulo' else '-->'} {node[t]}")
    for cls, style in _CLASS_STYLE.items():
        members = [node[i] for i in ids if _class_of(kb.entities[i]) == cls]
        if members:
            out.append(f"  classDef c{cls.replace('-', '')} {style}")
            out.append(f"  class {','.join(members)} c{cls.replace('-', '')}")
    out.append("```")
    return "\n".join(out) + "\n"


def view_rests_on(kb) -> str:
    out = [GENERATED, "# What rests on X", "",
           "For every object that something depends on: everything that rests on it, "
           "transitively (`depends_on`, and `implies` for assumptions), indented by depth. "
           "If X falls, re-check each line. Generated by `registry.py build`; the same "
           "list for one id is `registry.py usedby ID --transitive`.", ""]
    for e in _objects(kb):
        hits = walk(kb, e.id, lambda x: _usedby_of(kb, x), True)
        if not hits:
            continue
        out += [f"## {_vlink(e)} · {cell(status_cell(e))}", ""]
        for n, depth in hits:
            u = kb.entities.get(n)
            label = _vlink(u) if u else n
            st = status_cell(u) if u else "(unresolved)"
            out.append("  " * (depth - 1) + f"- {label} · {st}")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


