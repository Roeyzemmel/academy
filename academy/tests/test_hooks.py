@unittest.skipUnless(HAVE_GIT, "git is not on PATH")
class TicketOwnershipTests(TicketEditCheckTests):
    """Field ownership against the board's git HEAD."""

    def committed_ticket(self, tid="T-0010", **kw):
        self.init_board_repo()
        p = self.write(self.tpath("expert@t", tid),
                       ticket_text(tid, "author@t", "expert@t", **kw))
        self.commit_all()
        return p

    def edit(self, path, **changes):
        with open(path, "r", encoding="utf-8") as fh:
            meta, body = ac.read_frontmatter(fh.read())
        thread = changes.pop("_thread", None)
        body_fn = changes.pop("_body", None)
        meta.update(changes)
        if thread:
            body = ac.append_thread(body, thread[0], thread[1], date="2026-09-28")
        if body_fn:
            body = body_fn(body)
        self.write(path, ac.write_frontmatter(meta, body))

    def test_sender_may_not_accept(self):
        p = self.committed_ticket()
        self.edit(p, status="accepted")
        reason = self.check(p, "author:math-writer", cwd=self.author_home)
        self.assertIn("status open -> accepted", reason)
        self.assertIn("receiver", reason)

    def test_receiver_may_accept(self):
        p = self.committed_ticket()
        self.edit(p, status="accepted",
                  _thread=("expert@t/review-chair", "status open -> accepted"))
        reason = self.check(p, "expert:review-chair", cwd=self.expert_home)
