# --------------------------------------------------------------------------- names

def normalize(s: str) -> str:
    """Case-, whitespace- and punctuation-insensitive form of a label."""
    s = s.replace("\u2032", "'").lower()
    for long, short in WORD_FORMS:
        s = re.sub(rf"\b{long}\b", short, s)
    s = re.sub(r"(?<!\d)\.|\.(?!\d)", "", s)
    return re.sub(r"[\s,\-_:;()\[\]{}/\"]", "", s)


def prefix_of(eid: str) -> str:
    return "Q" if re.match(r"^Q\d+$", eid) else eid.split("-")[0]


def natural_key(s: str):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def entity_sort_key(e, order=()):
    p = prefix_of(e.id)
    order = list(order)
    rank = order.index(p) if p in order else len(order)
    return (rank, natural_key(e.id))


