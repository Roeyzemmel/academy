@dataclass
class Entity:
    id: str
    etype: str
    path: str                      # posix path relative to the root
    meta: dict
    body: str
    usedby: list = field(default_factory=list)
    example_claims: list = field(default_factory=list)
    implied_by: list = field(default_factory=list)
    v2: dict = None                # the frontmatter as written, for a schema-v2 file
    folder: str = ""               # objects layout: the kind folder it sits in


class KB:
    def __init__(self, root):
        self.root = Path(root)
        self.layout = "objects" if objects_layout(self.root) else "legacy"
        self.rules = rules_of(self.root)
        self.entities: dict[str, Entity] = {}
        self.by_norm: dict[str, str] = {}     # normalized id or alias -> id
        self.id_norms: set[str] = set()
        self.path_to_id: dict[str, str] = {}
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def error(self, where, msg):
        self.errors.append(f"{where}: {msg}")

    def warn(self, where, msg):
        self.warnings.append(f"{where}: {msg}")

    def sorted(self, types=None):
        ents = [e for e in self.entities.values() if types is None or e.etype in types]
        return sorted(ents, key=self.sort_key)

    def sort_key(self, e):
        return entity_sort_key(e, self.rules.order)


def objects_layout(root) -> bool:
    """Whether the home at ``root`` is in the notebook layout (R6): it has ``objects/``."""
    return (Path(root) / "objects").is_dir()


def entity_dirs(root) -> list:
    """``[(relative dir, entity type, kind folder or '')]`` in load order."""
    if not objects_layout(root):
        return [(d, t, "") for d, t in ENTITY_DIRS]
    return ([(f"objects/{k}", t, k) for k, t in OBJECT_FOLDERS.items()]
            + [("computation/verdicts", "verdict", ""), ("audits", "verdict", ""),
               ("computation/runs", "run", ""), ("computation/specs", "spec", "")])


def object_dirs(root) -> list:
    """The relative directories holding claim/assumption/example (and direction) files."""
    return [d for d, t, _ in entity_dirs(root) if t not in LEDGER_TYPES]


def object_path(root, eid, v2kind) -> str:
    """Where a new record of v2 kind ``v2kind`` goes (relative, posix)."""
    if objects_layout(root):
        return f"objects/{v2kind}/{eid}.md"
    return f"{'assumptions' if v2kind == 'assumption' else 'claims'}/{eid}.md"


def _audit_files(d):
    """The ledger verdicts under ``audits/``: every ``.md`` below it, except README, the
    ``_``-prefixed folders and files (``_unparsed``, templates), and the review runs
    ``land_review`` writes (frontmatter ``run: A|B``), which ``reviews.py`` reads."""
    for p in sorted(d.rglob("*.md")):
        rel = p.relative_to(d).parts
        if p.name.lower() == "readme.md" or any(s.startswith("_") for s in rel):
            continue
        head = p.read_text(encoding="utf-8").split("\n---", 1)[0]
        if re.search(r"(?m)^run:\s*\"?[AB]\"?\s*$", head):
            continue
        yield p


def load_kb(root) -> KB:
    kb = KB(root)
    for rel_dir, etype, folder in entity_dirs(kb.root):
        d = kb.root / rel_dir
        if not d.is_dir():
            continue
        files = _audit_files(d) if rel_dir == "audits" else sorted(d.glob("*.md"))
        for p in files:
            if p.name.lower() != "readme.md":
                _load_file(kb, p, etype, folder)
    derived = _schema.derived_superseded_by(
        (e.id, e.v2) for e in kb.entities.values() if e.v2 is not None)
    for e in kb.entities.values():
        if e.v2 is not None and derived.get(e.id):
            e.meta["superseded_by"] = derived[e.id]
    _index_names(kb)
    _link(kb)
    return kb


def _load_file(kb, p, etype, folder=""):
    rel = p.relative_to(kb.root).as_posix()
    try:
        meta, body = split_document(p.read_text(encoding="utf-8"), rel)
    except FrontmatterError as exc:
        kb.errors.append(str(exc))
        return
    eid = meta.get("id", p.stem if etype in LEDGER_TYPES else None)
    if not isinstance(eid, str) or not eid:
        kb.error(rel, "missing 'id'")
        return
    if eid in kb.entities:
        kb.error(rel, f"duplicate id '{eid}' (also in {kb.entities[eid].path})")
        return
    v2 = None
    if etype not in LEDGER_TYPES and _schema.is_v2(meta):
        v2, meta = meta, v2_internal(meta, etype)
    kb.entities[eid] = Entity(eid, etype, rel, meta, body, v2=v2, folder=folder)
    kb.path_to_id[rel] = eid


def _tagged(note, tag):
    return note == tag or note.startswith(tag + ";") or note.startswith(tag + " ")


def v2_internal(v2, etype) -> dict:
    """The internal (kb.py-shaped) frontmatter of a schema-v2 file: see the module
    docstring. The status stays a v2 word."""
    m = {}
    skip = {"kind", "form", "tags", "evidence", "history", "lifecycle", "modulo",
            "domain", "statement", "proof", "where", "bears_on"}
    for k, v in v2.items():
        if k not in skip:
            m[k] = v
    kind = v2.get("form") or KIND_BACK.get(v2.get("kind"))
    if etype != "example" and kind:
        m["kind"] = kind
    if "tags" in v2:
        m["topics"] = v2["tags"]
    rows = [_schema.evidence_cells(r) for r in (v2.get("evidence") or [])
            if isinstance(r, str)]
    cleared = [r[1] for r in rows if r[0] == "verdict" and _tagged(r[4], CLEARED_NOTE)]
    if cleared:
        m["cleared_by"] = cleared
    runs = [r[1].rsplit("/", 1)[-1][:-3] for r in rows
            if r[0] == "experiment" and _tagged(r[4], RUN_NOTE)
            and r[1].startswith("computation/runs/") and r[1].endswith(".md")]
    if runs or (etype == "example"):
        m["runs"] = runs
    return m


def display_aliases(e) -> list:
    out = [a for a in e.meta.get("aliases", []) if isinstance(a, str)] \
        if isinstance(e.meta.get("aliases"), list) else []
    old = e.meta.get("old")
    if e.etype == "assumption" and isinstance(old, str) and old and old not in out:
        out.append(old)
    return out


def _index_names(kb):
    for e in kb.sorted():
        n = normalize(e.id)
        if n in kb.by_norm:
            kb.error(e.path, f"id '{e.id}' collides with '{kb.by_norm[n]}' after normalisation")
            continue
        kb.by_norm[n] = e.id
        kb.id_norms.add(n)
    for e in kb.sorted():
        for a in display_aliases(e):
            n = normalize(a)
            other = kb.by_norm.get(n)
            if other == e.id:
                continue
            if other is not None and n in kb.id_norms:
                kb.error(e.path, f"alias '{a}' of {e.id} collides with the id '{other}'")
            elif other is not None:
                kb.error(e.path, f"duplicate alias '{a}' (on {other} and {e.id})")
            else:
                kb.by_norm[n] = e.id


def lookup(kb, text):
    """Resolve an id or alias. Returns (id or None, resolved_via_alias)."""
    text = text.strip()
    if text in kb.entities:
        return text, False
    for cand in (text, text[:-1] if re.search(r"[a-z′']$", text) else None):
        if not cand:
            continue
        n = normalize(cand)
        if n in kb.by_norm:
            return kb.by_norm[n], n not in kb.id_norms
    return None, False


def resolved_list(kb, e, key) -> list:
    v = e.meta.get(key, [])
    if not isinstance(v, list):
        return []
    out = []
    for ref in v:
        rid, _ = lookup(kb, ref)
        if rid:
            out.append(rid)
    return out


def resolved_level(kb, e):
    lvl = e.meta.get("level")
    if not isinstance(lvl, str) or not lvl:
        return None
    rid, _ = lookup(kb, lvl)
    return rid


def _link(kb):
    for e in kb.sorted():
        for dep in resolved_list(kb, e, "depends_on"):
            if e.id not in kb.entities[dep].usedby:
                kb.entities[dep].usedby.append(e.id)
        for ex in resolved_list(kb, e, "examples"):
            if e.id not in kb.entities[ex].example_claims:
                kb.entities[ex].example_claims.append(e.id)
        if e.etype == "example":
            for c in resolved_list(kb, e, "claims"):
                if c not in e.example_claims:
                    e.example_claims.append(c)
        if e.etype == "assumption":
            for a in resolved_list(kb, e, "implies"):
                kb.entities[a].implied_by.append(e.id)
    for e in kb.entities.values():
        for lst in (e.usedby, e.example_claims, e.implied_by):
            lst.sort(key=lambda i: kb.sort_key(kb.entities[i]))


def implies_closure(kb, aid) -> set:
    """All assumptions implied by aid (including aid itself)."""
    seen, queue = {aid}, deque([aid])
    while queue:
        cur = kb.entities.get(queue.popleft())
        if cur is None:
            continue
        for nxt in resolved_list(kb, cur, "implies"):
            if nxt not in seen:
                seen.add(nxt)
                queue.append(nxt)
    return seen


def status_of(e) -> str:
    st = e.meta.get("status")
    if isinstance(st, str) and st:
        return st
    q2 = e.meta.get("q2")
    if isinstance(q2, str) and q2:
        return f"q2: {q2}"
    return "-"


def summary_of(e) -> str:
    for key in ("summary", "title"):
        v = e.meta.get(key)
        if isinstance(v, str) and v:
            return v
    return ""


def fmt_line(kb, eid) -> str:
    e = kb.entities.get(eid)
    if e is None:
        return f"{eid} · (unresolved) ·"
    return f"{e.id} · {status_of(e)} · {summary_of(e)}"


def section(body: str, name: str):
    """Return the '## name' section of a body (heading included), or None."""
    lines = body.split("\n")
    start = next((i for i, l in enumerate(lines)
                  if l.rstrip("\r").strip().lower() == f"## {name}".lower()), None)
    if start is None:
        return None
    end = next((j for j in range(start + 1, len(lines))
                if re.match(r"^#{1,2} ", lines[j])), len(lines))
    return "\n".join(lines[start:end]).rstrip() + "\n"


def entity_history(e) -> list:
    """The history of an entity, oldest first: the body section (v1) or the frontmatter
    rows (v2, newest first there)."""
    if e.v2 is None:
        return parse_history(e.body)
    out = []
    for row in reversed(e.v2.get("history") or []):
        d, s, note = _schema.history_cells(row)
        out.append({"date": d, "text": f"{s}: {note}" if s else note})
    return out


def parse_history(body: str) -> list:
    sec = section(body, "History") or ""
    out = []
    for line in sec.split("\n"):
        m = HISTORY_LINE.match(line)
        if m:
            out.append({"date": m.group(1), "text": m.group(2).strip()})
    return out


