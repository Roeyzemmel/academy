def write_view(root: Path, rel: str, content: str, written: list):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    if p.exists() and p.read_text(encoding="utf-8") == content:
        return
    p.write_text(content, encoding="utf-8", newline="\n")
    written.append(rel)


def do_build(kb, quiet=False) -> int:
    run_check(kb)
    rc = report_check(kb, quiet)
    if rc:
        print("build: aborted, fix the errors above first")
        return rc
    written, root = [], kb.root
    write_view(root, "STATUS.md", view_status(kb), written)
    write_view(root, "INDEX.md", view_index(kb), written)
    write_view(root, "OPEN.md", view_open(kb), written)
    write_view(root, assumptions_view_path(kb), view_assumptions(kb), written)
    if kb.layout == "objects":
        write_view(root, f"{VIEWS_DIR}/INDEX.md", view_objects(kb), written)
        write_view(root, f"{VIEWS_DIR}/directions.md", view_directions(kb), written)
        write_view(root, f"{VIEWS_DIR}/graph.md", view_graph(kb), written)
        write_view(root, f"{VIEWS_DIR}/rests-on.md", view_rests_on(kb), written)
    write_view(root, "computation/verdicts.md", view_ledger(
        kb, "verdict", "Verdicts", ["date", "kind", "subjects", "clears", "decision"]), written)
    write_view(root, "computation/runs.md", view_ledger(
        kb, "run", "Runs", ["status", "family", "script", "class_short"]), written)
    data = export_json(kb)
    write_view(root, "kb/claims.json",
               json.dumps(data, ensure_ascii=False, indent=1) + "\n", written)
    write_sqlite(kb, root / "kb" / "kb.sqlite")
    written.append("kb/kb.sqlite")
    href = os.path.relpath(library_dir(root), root / "site").replace(os.sep, "/") + "/"
    write_view(root, "site/index.html", render_site(dict(data, papers_href=href)), written)
    fill_topic_pages(kb, written)
    if not quiet:
        print("build: wrote " + (", ".join(written) if written else "nothing (all up to date)"))
    return 0


