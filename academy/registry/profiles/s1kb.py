def _check_types(kb, e):
    for k, v in e.meta.items():
        if k in LIST_FIELDS and not isinstance(v, list):
            kb.error(e.path, f"'{k}' must be a list")
        elif k in MAP_FIELDS and not isinstance(v, dict):
            kb.error(e.path, f"'{k}' must be a nested map")
        elif k in SCALAR_FIELDS and not isinstance(v, str):
            kb.error(e.path, f"'{k}' must be a scalar")
    for k in REQUIRED[e.etype]:
        if k == "status" and e.meta.get("kind") in UNLABELLED_KINDS:
            continue
        if k == "summary" and e.v2 is not None:
            continue    # v2: the core schema has no summary; the title stands in
        if k not in e.meta:
            kb.error(e.path, f"missing required field '{k}'")


def _check_schema(kb, e):
    _check_types(kb, e)
    m = e.meta
    allowed = kb.rules.allowed()
    if e.etype in ("claim", "assumption", "example", "direction"):
        if not kb.rules.id_ok(e.id):
            kb.error(e.path, (f"id '{e.id}' is not PREFIX-<number or token> with a known prefix"
                              if kb.rules.prefixes else f"id '{e.id}' is not a slug"))
        elif e.etype in allowed and prefix_of(e.id) not in allowed[e.etype]:
            kb.error(e.path, f"prefix '{prefix_of(e.id)}' does not belong in {e.etype} files")
    kind = m.get("kind")
    if e.etype in ("claim", "assumption") and kind is not None and kind not in KINDS:
        kb.error(e.path, f"kind '{kind}' is not one of {'|'.join(KINDS)}")
    if e.etype == "assumption" and kind not in (None, "assumption"):
        kb.error(e.path, "an assumption file must have kind 'assumption'")
    st = m.get("status")
    labels = list(_schema.STATUSES) if e.v2 is not None else STATUS_LABELS
    if kind in UNLABELLED_KINDS:
        if st:
            kb.error(e.path, f"a {kind} is not a claim and carries no status label")
    elif e.etype in ("claim", "assumption") and st is not None and st not in labels:
        kb.error(e.path, f"status '{st}' is not one of: {' | '.join(labels)}")
    sbl = m.get("status_by_level")
    for lvl, v in (sbl.items() if isinstance(sbl, dict) else []):
        if v not in labels:
            kb.error(e.path, f"status_by_level[{lvl}] = '{v}' is not a status label")
    if e.v2 is not None:
        _check_v2(kb, e)
    added = m.get("added")
    if isinstance(added, str) and added and not DATE_RE.match(added):
        kb.warn(e.path, f"added '{added}' is not YYYY-MM-DD")
    if e.etype == "claim":
        for k in ("title", "summary"):
            if m.get(k) == "":
                kb.warn(e.path, f"'{k}' is empty")
        if isinstance(m.get("summary"), str) and len(m["summary"]) > 200:
            kb.warn(e.path, "summary is longer than 200 characters")


def _check_v2(kb, e):
    """The core's generic rules on the file as written, and the v2 links of this home."""
    extra = S1_EXTENSION
    for level, msg in _schema.check_record(e.v2, extra_fields=extra):
        (kb.error if level == "error" else kb.warn)(e.path, msg)
    v = e.v2
    want_kind = {"claim": ("claim", "conjecture", "question", "definition", "direction"),
                 "assumption": ("assumption",), "example": ("example",),
                 "direction": ("direction",)}.get(e.etype)
    if e.folder:
        if v.get("kind") != e.folder:
            kb.error(e.path, f"kind '{v.get('kind')}' belongs in objects/{v.get('kind')}/, "
                             f"not objects/{e.folder}/")
    elif want_kind and v.get("kind") not in want_kind:
        kb.error(e.path, f"kind '{v.get('kind')}' does not belong in {e.etype} files")
    form = v.get("form")
    if form is not None and form not in KINDS:
        kb.error(e.path, f"form '{form}' is not one of {'|'.join(KINDS)}")
    elif form is not None and KIND_V2.get(form) not in (v.get("kind"), None):
        kb.error(e.path, f"form '{form}' is a {KIND_V2.get(form)}, not a {v.get('kind')}")
    for item in v.get("modulo") or []:
        if isinstance(item, str) and (kb.rules.looks_like_id(item.strip()) or
                                      _schema.looks_like_id(item)):
            if ":" not in item:
                _check_ref(kb, e, "modulo", item)
        else:
            # plan section 6: `modulo: [ids]`, promoted along the graph once the target
            # is proved; free text cannot be followed
            kb.warn(e.path, f"modulo: {str(item)[:60]!r} is not a record id, so the claim "
                            "cannot be promoted along the graph when its input is proved")
    for key in ("supersedes", "bears_on"):
        for ref in v.get(key) or []:
            if isinstance(ref, str) and ":" not in ref:
                _check_ref(kb, e, key, ref)
    for row in v.get("evidence") or []:
        t, ref = _schema.evidence_cells(row)[:2]
        if t in ("verdict", "experiment", "audit") and ref and RE_REVIEW_REF.match(ref):
            p = review_ref_path(kb.root, ref)
            if p is not None and not p.is_file():   # None: the library is not beside us
                kb.error(e.path, f"evidence ref '{ref}' is not a file")
        elif t in ("verdict", "experiment", "audit") and ref and "://" not in ref \
                and ":" not in ref.split("/")[0] and not (kb.root / ref).is_file():
            kb.error(e.path, f"evidence ref '{ref}' is not a file")


def _check_ref(kb, e, key, ref, want=None):
    if not isinstance(ref, str):
        return None
    rid, via_alias = lookup(kb, ref)
    if rid is None:
        kb.error(e.path, f"{key}: '{ref}' does not resolve")
        return None
    if want and kb.entities[rid].etype not in want:
        kb.error(e.path, f"{key}: '{ref}' is a {kb.entities[rid].etype}, expected {'/'.join(want)}")
    elif via_alias:
        kb.warn(e.path, f"{key}: '{ref}' is an alias of {rid}; cite the id")
    return rid


def library_dir(root) -> Path:
    """The Expert's library as seen from the home at ``root``: the home of the first
    Expert instance of workspace.json ($ACADEMY_HOME_<INSTANCE> overrides it); a
    nonexistent path (so the index is empty) when the workspace names none."""
    for inst in _workspace.instances_of_role("expert"):
        home = _workspace.instance_home(inst, root)
        if home is not None:
            return Path(home)
    return Path(root).parent / "no-library"


def papers_index(kb) -> dict:
    """bibkey -> 'authors, short title' from the library's index.md (empty if it is absent)."""
    if getattr(kb, "_papers", None) is None:
        kb._papers = {}
        idx = library_dir(kb.root) / "index.md"
        if idx.is_file():
            for line in idx.read_text(encoding="utf-8").splitlines():
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                if len(cells) > 2 and re.match(r"^[A-Za-z][\w-]*$", cells[0]) and cells[0] != "key":
                    kb._papers[cells[0]] = cells[1]
    return kb._papers


def _check_refs(kb, e):
    m = e.meta
    targets = {"depends_on": None, "supersedes": None, "superseded_by": None,
               "examples": {"example"}, "clears": None, "subjects": None,
               "implies": {"assumption"}, "implies_pending": {"assumption"},
               "incomparable_with": {"assumption"}}
    if e.etype == "example":
        targets["claims"] = None
    for key, want in targets.items():
        for ref in m.get(key, []) if isinstance(m.get(key), list) else []:
            _check_ref(kb, e, key, ref, want)
    if isinstance(m.get("level"), str) and m["level"]:
        _check_ref(kb, e, "level", m["level"], {"assumption"})
    for p in m.get("cleared_by", []) if isinstance(m.get("cleared_by"), list) else []:
        if RE_REVIEW_REF.match(str(p)):
            full = review_ref_path(kb.root, p)
            if full is not None and not full.is_file():
                kb.error(e.path, f"cleared_by: '{p}' is not a file")
        elif not (kb.root / p).is_file():
            kb.error(e.path, f"cleared_by: '{p}' is not a file")
    for key in m.get("cites", []) if isinstance(m.get("cites"), list) else []:
        if key not in papers_index(kb):
            kb.warn(e.path, f"cites: '{key}' is not in the shared library ({library_dir(kb.root)}/index.md) "
                            "(add it there with /expert:cite, or fix the key)")
    if e.etype == "example" and isinstance(m.get("runs"), list):
        for r in m["runs"]:
            if lookup(kb, r)[0] is None:
                kb.warn(e.path, f"runs: '{r}' is not a run file")


def _check_supersession(kb):
    for e in kb.sorted():
        for t in resolved_list(kb, e, "supersedes"):
            if e.id not in resolved_list(kb, kb.entities[t], "superseded_by"):
                kb.error(e.path, f"{e.id} supersedes {t}, but {t} has no superseded_by: {e.id}")
        for t in resolved_list(kb, e, "superseded_by"):
            if e.id not in resolved_list(kb, kb.entities[t], "supersedes"):
                kb.error(e.path, f"{e.id} is superseded_by {t}, but {t} has no supersedes: {e.id}")


def _check_assumptions(kb):
    for e in kb.sorted({"assumption"}):
        for b in resolved_list(kb, e, "incomparable_with"):
            other = kb.entities[b]
            if e.id not in resolved_list(kb, other, "incomparable_with"):
                kb.error(e.path, f"{e.id} incomparable_with {b}, but not the reverse")
            if b in implies_closure(kb, e.id) or e.id in implies_closure(kb, b):
                kb.error(e.path, f"{e.id} and {b} are incomparable, yet an implies-path joins them")


def _check_proved_deps(kb):
    for e in kb.sorted({"claim"}):
        if e.meta.get("status") not in PROVED:
            continue
        for d in resolved_list(kb, e, "depends_on"):
            dep = kb.entities[d]
            if dep.meta.get("kind") in UNLABELLED_KINDS | {"question"}:
                continue  # definitions and remarks carry no label; a question is a subject, not an input
            if dep.etype == "claim" and dep.meta.get("status") not in PROVED:
                kb.warn(e.path, f"{e.meta.get('status')}, but depends_on {d} which is "
                                f"'{dep.meta.get('status')}'")


def first_body_status(body: str):
    for line in body.split("\n"):
        s = line.strip()
        if not (s.startswith("#") or "**" in s):
            continue
        m = STATUS_PHRASE.search(s)
        if m:
            found = m.group(1).lower()
            return next(lbl for lbl in STATUS_LABELS if lbl.lower() == found)
    return None


def _check_body_status(kb, e):
    st = e.meta.get("status")
    labels = list(_schema.STATUSES) if e.v2 is not None else STATUS_LABELS
    if e.etype != "claim" or st not in labels:
        return
    phrase = first_body_status(e.body)
    if phrase is None or phrase == st:
        return
    if phrase == "Proved" and st in ("Proved modulo stated inputs", "proved-modulo"):
        return
    if e.v2 is not None and _projection.project(phrase, _projection.S1) == \
            _projection.project(st, _projection.V2):
        return      # the body keeps its v1 words; the classes agree
    if e.meta.get("body_status_ack"):  # a reviewed, deliberate mismatch; the field says why
        return
    kb.warn(e.path, f"body's first status phrase is '{phrase}' but frontmatter says '{st}'")


def run_check(kb):
    """Run every check; errors and warnings accumulate on kb."""
    for e in kb.sorted():
        _check_schema(kb, e)
        _check_refs(kb, e)
        _check_body_status(kb, e)
    _check_supersession(kb)
    _check_assumptions(kb)
    _check_proved_deps(kb)
    return kb.errors, kb.warnings


def report_check(kb, quiet=False) -> int:
    for msg in kb.errors:
        print(f"ERROR {msg}")
    if not quiet:
        for msg in kb.warnings:
            print(f"WARNING {msg}")
        print(f"check: {len(kb.entities)} entities, {len(kb.errors)} errors, "
              f"{len(kb.warnings)} warnings")
    return 1 if kb.errors else 0


