def iter_edges(kb):
    for e in kb.sorted():
        for key in ("depends_on", "supersedes", "superseded_by", "examples", "implies",
                    "incomparable_with", "clears", "subjects", "claims"):
            for ref in e.meta.get(key, []) if isinstance(e.meta.get(key), list) else []:
                yield e.id, lookup(kb, ref)[0] or ref, key
        for p in e.meta.get("cleared_by", []) if isinstance(e.meta.get("cleared_by"), list) else []:
            yield e.id, verdict_id(kb, p), "cleared_by"
        lvl = e.meta.get("level")
        if isinstance(lvl, str) and lvl:
            yield e.id, lookup(kb, lvl)[0] or lvl, "level"


def write_sqlite(kb, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    if tmp.exists():
        tmp.unlink()
    con = sqlite3.connect(tmp)
    fill_sqlite(kb, con)
    con.commit()
    con.close()
    os.replace(tmp, path)


def fill_sqlite(kb, con):
    """Create and fill kb.sqlite's tables on connection ``con``."""
    con.executescript("""
        CREATE TABLE meta(key TEXT PRIMARY KEY, value TEXT);
        CREATE TABLE entities(id TEXT PRIMARY KEY, type TEXT, path TEXT, kind TEXT,
            status TEXT, status_note TEXT, level TEXT, title TEXT, summary TEXT,
            source TEXT, added TEXT, topics TEXT, frontmatter TEXT, body TEXT);
        CREATE TABLE aliases(alias TEXT, id TEXT, normalized TEXT);
        CREATE TABLE edges(src TEXT, dst TEXT, kind TEXT);""")
    con.execute("INSERT INTO meta VALUES ('generated', ?)", (GENERATED_TEXT,))
    for e in kb.sorted():
        g = lambda k: e.meta.get(k) if isinstance(e.meta.get(k), str) else None  # noqa: E731
        topics = ",".join(e.meta.get("topics", [])) if isinstance(e.meta.get("topics"), list) else None
        con.execute("INSERT INTO entities VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (e.id, e.etype, e.path, g("kind"), g("status"), g("status_note"),
                     g("level"), g("title"), g("summary"), g("source"), g("added"), topics,
                     json.dumps(e.meta, ensure_ascii=False), e.body))
        for a in display_aliases(e):
            con.execute("INSERT INTO aliases VALUES (?,?,?)", (a, e.id, normalize(a)))
    con.executemany("INSERT INTO edges VALUES (?,?,?)", list(iter_edges(kb)))


MARKER_RE = re.compile(r"(<!-- kb:list topic=([^\s>]+) -->)(.*?)(<!-- /kb:list -->)", re.S)


def topic_list(kb, topic, note_dir) -> list:
    out = []
    for e in kb.sorted():
        topics = e.meta.get("topics")
        if isinstance(topics, list) and topic in topics:
            out.append(f"- {md_link(e.id, rel_from(note_dir, e.path))} — {status_cell(e)} "
                       f"— {summary_of(e)}")
    return out or ["_(no items)_"]


def fill_markers(kb, text, note_dir) -> str:
    nl = "\r\n" if "\r\n" in text else "\n"

    def repl(m):
        items = topic_list(kb, m.group(2), note_dir)
        return m.group(1) + nl + nl.join(items) + nl + m.group(4)
    return MARKER_RE.sub(repl, text)


def fill_topic_pages(kb, written):
    pages = []
    for rel in ("notes", "objects/direction"):
        if (kb.root / rel).is_dir():
            pages += sorted((kb.root / rel).rglob("*.md"))
    for p in pages:
        with open(p, encoding="utf-8", newline="") as fh:
            text = fh.read()
        if "<!-- kb:list" not in text:
            continue
        note_dir = p.parent.relative_to(kb.root).as_posix()
        new = fill_markers(kb, text, note_dir)
        if new != text:
            with open(p, "w", encoding="utf-8", newline="") as fh:
                fh.write(new)
            written.append(p.relative_to(kb.root).as_posix())


