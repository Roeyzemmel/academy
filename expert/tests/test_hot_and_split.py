class SplitRecordsTests(unittest.TestCase):
    """Card status, review records, and the manifest round trip (Group F)."""

    def setUp(self):
        self.sb = fixtures.Sandbox()
        self.out = os.path.join(self.sb.root, "out")

    def tearDown(self):
        self.sb.close()

    def test_card_status_never_repairs_the_quote(self):
        _w, stats = ls.convert_sources(SOURCES, self.out, self.sb.lib, {"ABC21", "XY20"})
        meta, body = cards.read_card(os.path.join(self.out, "cards", "ABC21", "lemma-2-1.md"))
        self.assertEqual(meta["status"], "verified")
        meta, body = cards.read_card(os.path.join(self.out, "cards", "ABC21",
                                                  "theorem-3-4.md"))
        self.assertEqual(meta["status"], "unverified")
        self.assertIn("not found", meta["status_reason"])
        self.assertIn("Every nice surface is illuminated.", body)   # quote kept as given
        meta, _ = cards.read_card(os.path.join(self.out, "cards", "ABC21", "entry.md"))
        self.assertEqual(meta["status"], "unverified")
        self.assertIn("no verbatim quote", meta["status_reason"])
        self.assertEqual(sum(stats["status"].values()), stats["cards"])

    def test_verified_status_with_failing_quote_is_an_error(self):
        meta = {"key": "ABC21", "pinpoint": "Thm 9", "version": "v2", "read_from": "extraction",
                "status": "verified"}
        text = cards.render_card(meta, "S.", ["H."], "A sentence that the source never says.")
        m, b = ac.read_frontmatter(text)
        errs, _w, _q = cards.validate_card(m, b, self.sb.lib)
        self.assertTrue(any("status verified" in e for e in errs))

    def test_extract_quote_needs_an_anchor_nearby(self):
        b = ('- **X** which the proposition reads off the tiling ("a long parenthetical '
             'remark here"), so this is fine.')
        self.assertEqual(ls.extract_quote(b), "")

    def test_extract_quote_skips_a_heading_named_before_the_colon(self):
        # AW21/1-point-marking: the ledger names the paragraph in quotes before the
        # colon that actually introduces the relied-on statement.
        b = ('- **X** verbatim from the source, unnumbered paragraph "Marked points on '
             'translation surfaces" in the Introduction: "Define an n-point marking '
             'over M to be an affine invariant submanifold."')
        self.assertEqual(ls.extract_quote(b),
                          "Define an n-point marking over M to be an affine invariant "
                          "submanifold.")

    def test_extract_quote_skips_two_headings_named_before_the_colon(self):
        # AW21/scope-of-aw21-s-base-stratum-no-marked-points: two headings quoted back
        # to back before the real colon-introduced quote.
        b = ('- **X** Verbatim from `AW21.src/main.tex:277,279` (S1, "Affine invariant '
             'submanifolds" / "Marked points on translation surfaces" paragraphs, '
             'immediately before `L:FiberDim`): "Given a partition of the stratum into '
             'pieces of positive integers."')
        self.assertEqual(ls.extract_quote(b),
                          "Given a partition of the stratum into pieces of positive "
                          "integers.")

    def test_extract_quote_finds_a_pinpoint_quote_with_no_anchor_word(self):
        # MS91/lemma-4-2: a bare "(`key.txt:lines`): \"quote\"" with no "verbatim",
        # "quoted" or "reads" anywhere in the bullet.
        b = ('- **LEMMA 4.2** (`MS91.txt:1033-1034`): "The map is injective and for '
             'distinct points the sets are disjoint."')
        self.assertEqual(ls.extract_quote(b),
                          "The map is injective and for distinct points the sets are "
                          "disjoint.")

    def test_extract_quote_pinpoint_fallback_does_not_fire_on_a_cref(self):
        # Vo96a/verdict-against-prop-vorobets-lift: a \cref/\cite citation (no
        # backtick file:line pinpoint) must not be mistaken for one, even though the
        # bullet's prose happens to say "reads off" nowhere near a real quotation.
        b = ('- **Verdict** notes that the paper already says: which \\cite[Prop. '
             '5.1]{Vo96a} reads off the tiling and which \\cref{prop:vorobets-lift} '
             'presupposes, so this is not a new mismatch worth a quote here at all.')
        self.assertEqual(ls.extract_quote(b), "")

    def test_verdicts_records_and_unparsed(self):
        pieces = []
        _w, st = ls.convert_verdicts(VERDICTS, self.out, pieces=pieces)
        self.assertEqual(st["records"], 2)
        self.assertEqual(len(st["unparsed"]), 1)
        a = os.path.join(self.out, "reviews", "paper", "lem-x", "2026-09-23-primary-model-pair",
                         "A.md")
        with open(a, encoding="utf-8") as fh:
            meta, body = ac.read_frontmatter(fh.read())
        self.assertEqual((meta["verdict"], meta["model"], meta["model_note"]),
                         ("CONFIRMED", "claude-fable-5-1", "primary"))
        self.assertIsNone(meta["run_id"])                   # never invented
        b = a.replace("A.md", "B.md")
        with open(b, encoding="utf-8") as fh:
            meta, _ = ac.read_frontmatter(fh.read())
        self.assertEqual(meta["model_note"], "fallback; primary is fable")
        dec = a.replace("A.md", "decision.md")
        with open(dec, encoding="utf-8") as fh:
            text = fh.read()
        self.assertIn("run A adds a finding", text)
        self.assertIn("outcome: stays blue", text)
        self.assertTrue(os.path.isfile(os.path.join(
            self.out, "reviews", "paper", "lem-x",
            "2026-09-23-primary-model-pair-same-day", "B.md")))
        self.assertTrue(os.path.isfile(os.path.join(self.out, "reviews", "_unparsed.md")))

    def test_manifest_round_trip(self):
        for name, text, conv in (
                ("sources", SOURCES, lambda t, p: ls.convert_sources(
                    t, self.out, self.sb.lib, {"ABC21", "XY20"}, pieces=p)),
                ("related_work", RELATED, lambda t, p: ls.convert_related(t, self.out,
                                                                          pieces=p)),
                ("verdicts", VERDICTS, lambda t, p: ls.convert_verdicts(t, self.out,
                                                                        pieces=p))):
            pieces = []
            conv(text, pieces)
            man, problems = ls.build_manifest(text, pieces, name, "author@main")
            self.assertEqual(problems, [], name)
            self.assertEqual(ls.render_manifest(self.out, man), text, name)

    def test_cli_and_views(self):
        src = self.sb.write("d/sources.md", SOURCES)
        self.sb.write("d/related_work.md", RELATED)
        self.sb.write("d/verdicts.md", VERDICTS)
        d = os.path.dirname(src)
        code, out, err = fixtures.run_script(
            "ledger_split.py", None,
            ["--sources", src, "--related", os.path.join(d, "related_work.md"),
             "--verdicts", os.path.join(d, "verdicts.md"), "--out", self.out,
             "--library", self.sb.lib])
        self.assertEqual(code, 0, err)
        with open(os.path.join(self.out, "ledger-split-report.md"), encoding="utf-8") as fh:
            rep = fh.read()
        self.assertIn("## Unmapped", rep)
        self.assertIn("_unparsed.md", rep)
        code, out, err = fixtures.run_script("ledger_views.py", None,
                                             ["--home", self.out, "--check", d])
        self.assertEqual(code, 0, out + err)
        code, out, err = fixtures.run_script("ledger_views.py", None, ["--home", self.out])
        self.assertEqual(code, 0, err)
        with open(os.path.join(self.out, "views", "author@main", "verdicts.md"),
                  encoding="utf-8") as fh:
            self.assertIn("generated by academy", fh.readline())


