def _fm_close(lines, path):
    if not lines or lines[0].rstrip("\r") != "---":
        raise FrontmatterError(f"{path}:1: no frontmatter")
    for i in range(1, len(lines)):
        if lines[i].rstrip("\r") == "---":
            return i
    raise FrontmatterError(f"{path}:1: frontmatter is not closed")


def _find_key(lines, close, key):
    return next((i for i in range(1, close) if re.match(rf"^{key}:", lines[i])), None)


def _set_key(lines, close, key, text, eol, after=None) -> int:
    """Replace line `key:` or insert it (after `after`, else before the fence)."""
    i = _find_key(lines, close, key)
    if i is not None:
        lines[i] = text + eol
        return close
    j = _find_key(lines, close, after) if after else None
    lines.insert(j + 1 if j is not None else close, text + eol)
    return close + 1


def _append_cleared_by(lines, close, vpath, eol, path) -> int:
    i = _find_key(lines, close, "cleared_by")
    if i is None:
        lines.insert(close, f"cleared_by: {format_list([vpath])}{eol}")
        return close + 1
    rest = lines[i].rstrip("\r")[len("cleared_by:"):]
    if not _is_skippable(rest):
        items = parse_value(rest, path, i + 1)
        if vpath not in items:
            lines[i] = f"cleared_by: {format_list(items + [vpath])}{eol}"
        return close
    last, j = i, i + 1
    while j < close and (lines[j][:1] in (" ", "\t", "-") or _is_skippable(lines[j])):
        if lines[j].lstrip().startswith("-"):
            last = j
        j += 1
    items = [parse_scalar(lines[k].strip()[2:], path, k + 1)
             for k in range(i + 1, last + 1) if lines[k].lstrip().startswith("- ")]
    if vpath in items:
        return close
    indent = lines[last][:len(lines[last]) - len(lines[last].lstrip())] if last > i else "  "
    lines.insert(last + 1, f"{indent}- {format_scalar(vpath)}{eol}")
    return close + 1


def _append_history(lines, close, entry, eol):
    h = next((i for i in range(close + 1, len(lines))
              if lines[i].rstrip("\r").strip() == "## History"), None)
    if h is None:
        while len(lines) > close + 1 and lines[-1].strip() == "":
            lines.pop()
        lines += ["" + eol, "## History" + eol, entry + eol, ""]
        return
    end = next((j for j in range(h + 1, len(lines)) if re.match(r"^#{1,2} ", lines[j])),
               len(lines))
    last = max([k for k in range(h + 1, end) if lines[k].strip()], default=h)
    lines.insert(last + 1, entry + eol)


def review_ref_path(root, ref):
    """The file named by an Expert review ref ``file:expert@<name>/reviews/...md``, as seen
    from the home at ``root`` (the library beside it, worktree suffix first). None when
    ``ref`` is no such ref, or workspace.json names no home for that instance."""
    m = RE_REVIEW_REF.match(str(ref or "").strip())
    if not m:
        return None
    home = _workspace.instance_home(m.group(1), root)
    return None if home is None else Path(home) / m.group(2)


def _review_ref_of(root, full):
    """The review ref of an absolute path inside an Expert home's ``reviews/``, else None."""
    for inst in _workspace.instances_of_role("expert"):
        home = _workspace.instance_home(inst, root)
        if home is None:
            continue
        try:
            rel = Path(full).resolve().relative_to(Path(home).resolve()).as_posix()
        except ValueError:
            continue
        ref = f"file:{inst}/{rel}"
        if RE_REVIEW_REF.match(ref):
            return ref
    return None


def verdict_path(root, vrel) -> Path:
    """The file of a verdict reference: a home-relative path, or an Expert review ref."""
    p = review_ref_path(root, vrel)
    return p if p is not None else Path(root) / vrel


def verdict_id(kb, ref):
    """The verdict entity a ``cleared_by`` ref names (its ledger id), else the ref. An
    Expert review ref names the verdict its file id does, while the home still holds that
    verdict's old copy (until phase 8)."""
    if ref in kb.path_to_id:
        return kb.path_to_id[ref]
    if RE_REVIEW_REF.match(str(ref)):
        stem = Path(str(ref)).stem
        if stem in kb.entities and kb.entities[stem].etype == "verdict":
            return stem
    return ref


def _verdict_relpath(root: Path, verdict: str):
    """The verdict reference ``set-status --verdict`` records: a path under
    VERDICT_DIRS relative to the home, or an Expert review ref (given as the ref or as
    a path into the library's ``reviews/``). None when it is neither, or no such file."""
    text = str(verdict).strip().replace("\\", "/")
    if RE_REVIEW_REF.match(text):
        p = review_ref_path(root, text)
        return text if p is not None and p.is_file() else None
    p = Path(verdict)
    full = p if p.is_absolute() else root / p
    try:
        rel = full.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        ref = _review_ref_of(root, full) if full.is_file() else None
        return ref
    if not rel.startswith(VERDICT_DIRS) or not full.is_file():
        return None
    if rel.startswith("audits/") and not objects_layout(root):
        return None
    return rel


def _verdict_row(root: Path, vrel, tag=CLEARED_NOTE):
    """The v2 evidence row of verdict file ``vrel``: its decision and id."""
    vid, decision = Path(vrel).stem, ""
    try:
        vmeta, _ = split_document(verdict_path(root, vrel).read_text(encoding="utf-8"), vrel)
        vid = str(vmeta.get("id") or vid)
        decision = str(vmeta.get("decision") or "")
    except (OSError, FrontmatterError):
        pass
    return _schema.evidence_row("verdict", vrel, decision, vid, tag)


# What a verdict file must record for a target (plan section 8): the verdict word each
# of its runs gives. v1 labels map as their v2 words do.
VERDICT_NEEDS = {"proved": "CONFIRMED", "proved-modulo": "CONFIRMED",
                 "refuted": "DISPROVED", "refuted-as-stated": "DISPROVED",
                 "supported": "SOUND", "Proved": "CONFIRMED",
                 "Proved modulo stated inputs": "CONFIRMED", "Disproved": "DISPROVED"}
_CONTRARY = {"CONFIRMED": ("DISPROVED", "GAP", "PLAUSIBLE"),
             "DISPROVED": ("CONFIRMED", "GAP", "PLAUSIBLE"),
             "SOUND": ("GAP", "BROKEN")}
_RE_RUN_LINE = re.compile(r"^Run [A-Z]\b(?!'s)[^:\n]*:(.*)$", re.M)


def _word(text):
    """The verdict word in ``text`` (one of the section-8 words), or ''."""
    t = " ".join(str(text or "").replace("_", " ").replace("-", " ").upper().split())
    if "REFUTATION CONFIRMED" in t or "DISPROVED" in t:
        return "DISPROVED"
    for w in ("SOUND MODULO", "CONFIRMED", "PLAUSIBLE", "GAP", "BROKEN", "SOUND"):
        if w in t:
            return w
    return ""


def _run_segments(body):
    """``[(head, segment)]`` for each ``Run X...:`` line of an s1 verdict file: the text
    after its colon, and the text up to the next such line (a verbatim VERDICT block)."""
    ms = list(_RE_RUN_LINE.finditer(body))
    return [(m.group(1), body[m.start():ms[i + 1].start() if i + 1 < len(ms) else len(body)])
            for i, m in enumerate(ms)]


def _run_word(head, segment=""):
    """The verdict of one run of an s1 verdict file: the ``confidence:`` of its head or
    of its VERDICT block, else the head's text before the first dash."""
    for text in (head, segment):
        m = re.search(r"confidence:\s*([A-Za-z _-]+?)\s*(?:[;\[\]\n]|$)", text)
        if m:
            return _word(m.group(1))
    return _word(re.split(r"\s[—–]\s|\s-\s", head.strip(), 1)[0])


def _fits(word, need):
    return word == need or (need == "SOUND" and word == "SOUND MODULO")


def _verdict_meta(root: Path, vrel):
    return _meta_of_file(verdict_path(root, vrel), vrel)


def _meta_of_file(path: Path, name):
    text = Path(path).read_text(encoding="utf-8")
    vrel = name
    try:
        meta, body = split_document(text, vrel)
    except FrontmatterError:
        from ..core import grounds as _g
        meta, body = _g.record_fields(text), text
    return meta or {}, body


def _own_prefixes(kb) -> tuple:
    """The ``<ns>:`` prefix that names this home's own objects: its namespace
    (academy.json ``ns``, else the workspace's), or ``s1:``, the profile's first home,
    when neither knows it. Another home's prefix (``s1:`` in ``flat``) names its object."""
    own = kb.rules.ns or _workspace.repo_ns(kb.root) or "s1"
    return (f"{own}:",)


def _ids(kb, v):
    """The ids of this home that ``v`` (an id or a list) names; ``<own ns>:<id>`` is
    read as ``<id>``, any other namespace names no object here."""
    vals = v if isinstance(v, list) else ([v] if v else [])
    own = _own_prefixes(kb)
    return {lookup(kb, str(x).split(":", 1)[-1] if str(x).startswith(own) else str(x))[0]
            for x in vals} - {None}


def verdict_file_problems(kb, vrel, eid, label, human=False):
    """Why verdict file ``vrel`` cannot carry ``eid`` to ``label`` (empty when it can).

    * A settling target (proved, proved-modulo, refuted*, supported) needs the file to
      clear the claim (``clears``) and, unless the human's word stands in for it, at
      least two ``Run X:`` lines giving the target's verdict word and none giving a
      contrary one. (Which of proved / proved-modulo the runs support is not read from
      the file: a verdict file may cover several items.)
    * A landed review record (``subject``, ``verdict``, ``run_id`` in its frontmatter)
      counts with the other runs landed beside it: two with distinct run ids and the
      target's verdict, all on this claim.
    * Any other target needs the file to name the claim (``subjects`` or ``clears``)."""
    try:
        meta, body = _verdict_meta(kb.root, vrel)
    except OSError as exc:
        return [f"{vrel}: cannot read ({exc})"]
    need = VERDICT_NEEDS.get(label)
    subjects = _ids(kb, meta.get("subjects")) | _ids(kb, meta.get("subject"))
    clears = _ids(kb, meta.get("clears"))
    if meta.get("verdict") and meta.get("run_id") and meta.get("subject"):
        if eid not in subjects:
            return [f"{vrel} is a review of {meta.get('subject')}, not {eid}"]
        if not need:
            return []
        runs = {}
        folder = verdict_path(kb.root, vrel).parent
        for f in sorted(folder.glob("*.md")):
            try:
                m, _ = _meta_of_file(f, f.name)
            except (OSError, ValueError):
                continue
            if m.get("run_id") and eid in _ids(kb, m.get("subject")):
                runs[str(m["run_id"])] = _word(m.get("verdict"))
        good = [r for r, w in runs.items() if _fits(w, need)]
        bad = [f"{r} {w}" for r, w in runs.items() if w in _CONTRARY[need]]
        probs = []
        if len(good) < 2 and not human:
            probs.append(f"{label} needs two landed runs giving {need} on {eid}; "
                         f"{vrel.rsplit('/', 1)[0]}/ has "
                         f"{len(good)}")
        if bad and not human:
            probs.append(f"runs landed beside {vrel} disagree: " + ", ".join(bad))
        return probs
    if not need:
        return [] if eid in subjects | clears else [
            f"{vrel} does not name {eid} (subjects / clears)"]
    probs = []
    if eid not in clears:
        probs.append(f"{vrel} does not clear {eid} (its clears: "
                     f"{', '.join(sorted(clears)) or 'none'})")
    if human:
        return probs
    segs = _run_segments(body)
    words = [_run_word(h, g) for h, g in segs]
    good = [w for w in words if _fits(w, need)]
    bad = sorted(set(w for w in words if w in _CONTRARY[need]))
    if len(good) < 2:
        probs.append(f"{label} needs two runs giving {need} in {vrel}; found "
                     + (", ".join(w or "?" for w in words) or "no 'Run X:' lines"))
    if bad:
        probs.append(f"{vrel} records contrary runs: {', '.join(bad)}")
    return probs


def rewrite_status_v2(p: Path, label, vrow, note, old, human=None):
    """set-status on a schema-v2 file: the status (or lifecycle) line, the verdict's
    evidence row (when there is a verdict), the status note, and a history row, newest
    first. Line-preserving."""
    doc = _Doc(p, _fm.format_scalar_single)
    after = V2_ORDER
    if label in _schema.LIFECYCLES:
        doc.set_scalar("lifecycle", label, after=after[:after.index("lifecycle")])
    else:
        doc.set_scalar("status", label, after=("form", "kind", "title"))
    if note is not None:
        doc.set_scalar("status_note", note, after=after[:after.index("status_note")])
    if vrow is not None:
        items = doc.list_items("evidence") or []
        if vrow not in items:
            doc.add_item("evidence", vrow, after=after[:after.index("evidence")])
        why = f"verdict {_schema.evidence_cells(vrow)[1]}"
    else:
        why = note or "no verdict"
    if human:
        why += f"; the human's word \"{human}\""
        if "|" in why:
            why = why.replace("|", "/")
    doc.add_item("history", _schema.history_row(
        today(), label, f"status {old} → {label} ({why})"),
        first=True, after=("evidence",))
    doc.save()


def cmd_set_status(args) -> int:
    kb = load_kb(args.root)
    eid0, _ = lookup(kb, args.id)
    v2 = eid0 is not None and kb.entities[eid0].v2 is not None
    labels = list(_schema.STATUSES) + list(_schema.LIFECYCLES[1:]) if v2 else STATUS_LABELS
    if args.label not in labels:
        print(f"set-status: '{args.label}' is not one of: {' | '.join(labels)}",
              file=sys.stderr)
        return 1
    # v2: an unsettled or lifecycle target may rest on a note instead of a verdict file
    no_verdict_ok = v2 and args.label not in VERDICT_NEEDS
    if args.verdict is None and not (no_verdict_ok and args.note):
        print("set-status: --verdict is required" + (
            " (or, for an unsettled or lifecycle target, --note)" if v2 else ""),
            file=sys.stderr)
        return 1
    vrel = None
    if args.verdict is not None:
        vrel = _verdict_relpath(kb.root, args.verdict)
        if vrel is None:
            print(f"set-status: '{args.verdict}' is not an existing file under "
                  + ("computation/verdicts/ or audits/" if kb.layout == "objects"
                     else "computation/verdicts/")
                  + ", nor an Expert review ref (file:expert@<name>/reviews/...)",
                  file=sys.stderr)
            return 1
    eid, _ = _resolve_or_complain(kb, args.id)
    if eid is None:
        return 1
    e = kb.entities[eid]
    if e.etype != "claim":
        print(f"set-status: {eid} is a {e.etype}, not a claim", file=sys.stderr)
        return 1
    if e.v2 is not None and vrel is not None:
        # plan section 8 on a v2 record: the verdict file must be about this claim and
        # record what the target needs (a v1 record keeps kb.py's behaviour)
        probs = verdict_file_problems(kb, vrel, eid, args.label, human=bool(args.human))
        if probs:
            print("set-status: refused:\n- " + "\n- ".join(probs), file=sys.stderr)
            return 1
    old = e.meta.get("status", "(none)")
    # superseded (v2): the replacing record carries the one-way `supersedes` link
    new = None
    if e.v2 is not None and args.label == "superseded":
        new, _ = lookup(kb, args.superseded_by or "")
        if new is None or kb.entities[new].v2 is None or new == eid:
            print("set-status: superseded needs --superseded-by, the id of the schema-v2 "
                  "record that replaces " + eid, file=sys.stderr)
            return 1
    path = kb.root / e.path
    touched = [(path, path.read_bytes())]
    if new is not None:
        npath = kb.root / kb.entities[new].path
        nv2 = kb.entities[new].v2
        sup = nv2.get("supersedes") or []
        if eid not in (sup if isinstance(sup, list) else [sup]):
            touched.append((npath, npath.read_bytes()))
            doc = _Doc(npath, _fm.format_scalar_single)
            doc.add_item("supersedes", eid, after=V2_ORDER[:V2_ORDER.index("supersedes")])
            doc.add_item("history", _schema.history_row(
                today(), _schema.state(nv2) or "", f"supersedes {eid}"),
                first=True, after=("evidence",))
            doc.save()
    if e.v2 is not None:
        old = _schema.state(e.v2) or "(none)"
        rewrite_status_v2(path, args.label,
                          _verdict_row(kb.root, vrel) if vrel else None,
                          args.note, old, human=args.human)
    else:
        rewrite_status_file(path, e.path, args.label, vrel, args.note, old)
    # the change stands only if the kb still builds: otherwise the files are put back
    # byte for byte, so a refusal never leaves a changed status behind
    rc = do_build(load_kb(args.root), quiet=True)
    if rc:
        for f, b in touched:
            f.write_bytes(b)
        print(f"set-status: refused: the kb does not build with {eid} at {args.label}; "
              + ", ".join(kb.entities[x].path for x in [eid] + ([new] if new else []))
              + " unchanged", file=sys.stderr)
        return rc
    print(f"{eid}: status {old} → {args.label} ("
          + (f"verdict {vrel}" if vrel else "no verdict file") + ")")
    return 0


def rewrite_status_file(p: Path, rel, label, vrel, note, old):
    text = p.read_bytes().decode("utf-8")
    lines = text.split("\n")
    eol = "\r" if lines[0].endswith("\r") else ""
    close = _fm_close(lines, rel)
    close = _set_key(lines, close, "status", f"status: {format_scalar(label)}", eol,
                     after="kind")
    if note is not None:
        close = _set_key(lines, close, "status_note",
                         f"status_note: {format_scalar(note)}", eol, after="status")
    close = _append_cleared_by(lines, close, vrel, eol, rel)
    _append_history(lines, close, f"- {today()}: status {old} → {label} (verdict {vrel})", eol)
    p.write_bytes("\n".join(lines).encode("utf-8"))


def attach_verdict(root, text, verdict):
    """Append the verdict file ``verdict`` to ``cleared_by`` of ``text``'s entity: the
    s1 form of attaching evidence (append-only, no status change, no build). Returns
    (entity id, verdict relpath); raises ValueError when either does not resolve."""
    kb = load_kb(root)
    vrel = _verdict_relpath(kb.root, verdict)
    if vrel is None:
        raise ValueError(f"'{verdict}' is not an existing file under computation/verdicts/"
                         + (" or audits/" if kb.layout == "objects" else ""))
    eid, _ = lookup(kb, text)
    if eid is None:
        raise ValueError(f"no entity or alias matches '{text}'")
    e = kb.entities[eid]
    p = kb.root / e.path
    if e.v2 is not None:
        row = _verdict_row(kb.root, vrel)
        doc = _Doc(p, _fm.format_scalar_single)
        if row not in (doc.list_items("evidence") or []):
            doc.add_item("evidence", row, after=V2_ORDER[:V2_ORDER.index("evidence")])
            doc.save()
        return eid, vrel
    lines = p.read_bytes().decode("utf-8").split("\n")
    eol = "\r" if lines[0].endswith("\r") else ""
    close = _fm_close(lines, e.path)
    _append_cleared_by(lines, close, vrel, eol, e.path)
    p.write_bytes("\n".join(lines).encode("utf-8"))
    return eid, vrel


def attach_row(root, text, row):
    """Append one schema-v2 evidence row (``type | ref | verdict | run_id | note``) to
    the v2 entity ``text`` (append-only; no status change). Returns the entity id;
    raises ValueError when the entity is missing or v1, or the row is malformed."""
    kb = load_kb(root)
    eid, _ = lookup(kb, text)
    if eid is None:
        raise ValueError(f"no entity or alias matches '{text}'")
    e = kb.entities[eid]
    if e.v2 is None:
        raise ValueError(f"{eid} is not a schema-v2 record; attach a verdict file instead")
    t, ref = _schema.evidence_cells(row)[:2]
    if str(row).count("|") < 4 or t not in _schema.EVIDENCE_TYPES or not ref:
        raise ValueError(f"not an evidence row `type | ref | verdict | run_id | note`: {row}")
    doc = _Doc(kb.root / e.path, _fm.format_scalar_single)
    if row in (doc.list_items("evidence") or []):
        raise ValueError("that evidence row is already recorded")
    doc.add_item("evidence", row, after=V2_ORDER[:V2_ORDER.index("evidence")])
    doc.save()
    return eid


def cmd_resolve(args) -> int:
    kb = load_kb(args.root)
    text = " ".join(args.text)
    seen = []
    for m in LABEL_RE.finditer(text):
        if m.group(0) not in seen:
            seen.append(m.group(0))
    for label in seen:
        eid, _ = lookup(kb, label)
        print(f"{label} → " + (fmt_line(kb, eid) if eid else "(unresolved)"))
    if not seen:
        print("(no old-style labels found)")
    return 0


