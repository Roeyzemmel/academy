def run_hook(script, event, env=None, cwd=None):
    """Run one hook script with ``event`` on stdin; return (returncode, parsed stdout|None)."""
    full_env = dict(os.environ)
    full_env.update(env or {})
    res = subprocess.run([sys.executable, os.path.join(SCRIPTS, script)],
                         input=json.dumps(event).encode("utf-8"),
                         capture_output=True, env=full_env, cwd=cwd, timeout=60)
    out = res.stdout.decode("utf-8").strip()
    return res.returncode, (json.loads(out) if out else None), res.stderr.decode(
        "utf-8", "replace")


def decision(out):
    return (out or {}).get("hookSpecificOutput", {}).get("permissionDecision")


def config_for(role, instance, ns=None, views=None):
    cfg = {"schema": 1, "role": role, "instance": instance,
           "domains": ["test-domain"],
           "paths": {k: k for k in ac.REQUIRED_PATHS[role]},
           "registry": {"profile": "none"}, role: {}}
    cfg["paths"]["views"] = views or ["views", "Drafts/statements.md"]
    if ns:
        cfg["ns"] = ns
        cfg["registry"] = {"profile": "paper", "root": "claims"}
    return cfg


def ticket_text(tid, frm, to, status="open", thread=None, **extra):
    meta = {"id": tid, "title": "Fixture " + tid, "kind": "verify", "from": frm,
            "to": to, "status": status, "priority": "normal", "ask": "Check it.",
            "deliverable": "A packet.", "refs": [], "blocks": [], "waiting_on": [],
            "budget": {"runs": 1, "max_model": "sonnet"}, "packets": [],
            "created": "2026-09-27", "updated": "2026-09-27"}
    meta.update(extra)
    text = ac.new_ticket(meta)
    for who, line in thread or [("human", "opened")]:
        meta2, body = ac.read_frontmatter(text)
        text = ac.write_frontmatter(meta2, ac.append_thread(body, who, line,
                                                            date="2026-09-27"))
    return text


def packet_text(pid, instance, state="open"):
    meta = {"packet": pid, "title": "Fixture " + pid, "instance": instance,
            "kind": "other", "by": instance, "state": state, "created": "2026-09-27"}
    body = ("\n## Summary\n\nA fixture.\n\n## Produced\n\nNothing.\n\n"
            "## Established vs assumed\n\nNothing.\n\n## Evidence\n\nNone.\n\n"
            "## Decisions needed\n\nNone.\n\n## Machine notes\n\nNone.\n\n## Decision\n\n")
    if state == "decided":
        body += "- D0: ack | 2026-09-27 | human\n"
    return ac.write_frontmatter(meta, body)


