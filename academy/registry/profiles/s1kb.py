def is_open(e) -> bool:
    st, kind = e.meta.get("status"), e.meta.get("kind")
    if e.etype != "claim":
        return False
    return st in ("Not settled",) + _schema.UNSETTLED or \
        (kind in ("open", "conj") and st not in PROVED + REFUTED)


