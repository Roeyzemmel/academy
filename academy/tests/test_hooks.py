"""Tests for the base plugin's hooks, fed JSON fixture events on stdin.

Each hook script is run as a subprocess exactly as Claude Code runs it, against a
throw-away workspace (``ACADEMY_WORKSPACE``), homes and board in a temp directory.
Run from the repo root:  py -m unittest discover academy/tests
"""

