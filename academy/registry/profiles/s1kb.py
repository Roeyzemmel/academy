def statement_text(e) -> str:
    """The statement a review is given on: the '## Statement' section, else the body."""
    sec = section(e.body, "Statement")
    return sec if sec is not None else e.body


def _edges_of(kb, e):
    for key in ("depends_on", "supersedes", "superseded_by", "examples", "implies",
                "incomparable_with", "clears", "subjects", "claims"):
        for ref in e.meta.get(key, []) if isinstance(e.meta.get(key), list) else []:
            yield lookup(kb, ref)[0] or ref, key
    if e.v2 is not None:
        for ref in e.v2.get("bears_on") or []:
            yield (lookup(kb, ref)[0] or ref) if ":" not in ref else ref, "bears_on"
        for ref in e.v2.get("modulo") or []:
            if isinstance(ref, str) and lookup(kb, ref)[0]:
                yield lookup(kb, ref)[0], "modulo"
    for p in e.meta.get("cleared_by", []) if isinstance(e.meta.get("cleared_by"), list) else []:
        yield verdict_id(kb, p), "cleared_by"
    lvl = e.meta.get("level")
    if isinstance(lvl, str) and lvl:
        yield lookup(kb, lvl)[0] or lvl, "level"


class S1Store(Store):
    """This namespace as the other profiles and the engine see it."""
    profile = "s1-kb"

    def __init__(self, ns, home):
        super().__init__(ns, home)
        self.kb = load_kb(home)
        self.errors = list(self.kb.errors)
        for e in self.kb.sorted():
            st = e.meta.get("status") if isinstance(e.meta.get("status"), str) else ""
            if e.etype not in ("claim", "assumption"):
                st = ""
            links = [(rel, f"{ns}:{dst}" if dst in self.kb.entities else dst)
                     for dst, rel in _edges_of(self.kb, e)]
            if e.v2 is not None:
                cls = _schema.project(e.v2) if st or e.v2.get("lifecycle") != "active" \
                    else _projection.NA
                st = _schema.state(e.v2) if e.etype in ("claim", "assumption") else ""
            else:
                cls = _projection.project(st, _projection.S1)
            self.records[e.id] = Record(
                ns=ns, type=e.etype, id=e.id, fields=e.meta, body=e.body,
                file=str(self.kb.root / e.path), status=st,
                cls=cls, title=summary_of(e), links=links)

    def lookup(self, name):
        rid, _ = lookup(self.kb, name)
        if rid is None:
            return None, False
        return rid, rid == name.strip()

    def aliases(self, rid):
        e = self.kb.entities.get(rid)
        return display_aliases(e) if e else []

    def statement_text(self, rid):
        e = self.kb.entities.get(rid)
        return statement_text(e) if e else None


