LOG = ("2026-09-28T10:00:00\tlibrary_lookup\tclerk\tABC21\n"
       "2026-09-28T10:01:00\tlibrary_lookup\thuman\tXY20\n"
       "2026-09-28T10:02:00\tlibrary_verify_quote\tlibrarian\tABC21\n"
       "2026-09-28T10:03:00\tlibrary_search\tclerk\tperiodic points finite\n"
       "2026-09-28T10:04:00\tlibrary_missing\thuman\t-\n"
       "2026-09-28T10:05:00\tclaims_show\tclerk\tpaper:lem:x\n"
       "garbage line\n")


class HotTests(unittest.TestCase):
    def setUp(self):
        self.sb = fixtures.Sandbox()
        self.log = self.sb.write("papers/.academy/access.log", LOG)
        self.sb.write("papers/cards/ABC21/lemma-2-1.md", fixtures.card_text())

    def tearDown(self):
        self.sb.close()

    def test_tally(self):
        keys, queries, claims = hot.tally(hot.read_log([self.log]))
        self.assertEqual(keys["ABC21"][0], 2)
        self.assertEqual(keys["XY20"][0], 1)
        self.assertEqual(list(queries), ["periodic points finite"])
        self.assertEqual(list(claims), ["paper:lem:x"])

    def test_build_orders_and_marks(self):
        text = hot.build(self.sb.lib, [self.log], 50)
        self.assertTrue(text.startswith("<!-- generated by academy: expert/scripts/hot.py"))
        self.assertLess(text.index("### ABC21"), text.index("### XY20"))
        self.assertIn("**Lemma 2.1**", text)
        self.assertIn("The orbit of a periodic point is finite.", text)
        self.assertIn('Able-Baker-Charlie, "A paper"', text)
        self.assertIn("`paper:lem:x`", text)

    def test_size_limits(self):
        text = hot.build(self.sb.lib, [self.log], 1)
        self.assertIn("### ABC21", text)
        self.assertNotIn("### XY20", text)

    def test_tie_broken_by_latest(self):
        log = self.sb.write("papers/l2.log", "2026-09-01T00:00:00\tlibrary_lookup\tx\tAAA\n"
                                             "2026-09-02T00:00:00\tlibrary_lookup\tx\tZZZ\n")
        keys, _, _ = hot.tally(hot.read_log([log]))
        self.assertEqual([k for k, _ in hot.top(keys, 5)], ["ZZZ", "AAA"])

    def test_cli_writes_hot_md(self):
        code, out, err = fixtures.run_script("hot.py", None, ["--home", self.sb.lib])
        self.assertEqual(code, 0, err)
        self.assertIn("### ABC21", self.sb.read("papers/hot.md"))


