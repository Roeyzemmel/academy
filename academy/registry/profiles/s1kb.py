def _resolve_or_complain(kb, text):
    eid, via = lookup(kb, text)
    if eid is None:
        print(f"no entity or alias matches '{text}'", file=sys.stderr)
    return eid, via


def cmd_check(args) -> int:
    kb = load_kb(args.root)
    run_check(kb)
    files = getattr(args, "files", None)
    if files:
        rels = set()
        for f in files:
            p = Path(f)
            p = p if p.is_absolute() else Path.cwd() / p
            try:
                rels.add(p.resolve().relative_to(kb.root.resolve()).as_posix())
            except ValueError:
                rels.add(str(f).replace("\\", "/"))
        mine = lambda m: any(m == r or m.startswith(r + ":") for r in rels)  # noqa: E731
        kb.errors = [m for m in kb.errors if mine(m)]
        kb.warnings = [m for m in kb.warnings if mine(m)]
    return report_check(kb)


