class SplitTests(unittest.TestCase):
    def setUp(self):
        self.sb = fixtures.Sandbox()
        self.out = os.path.join(self.sb.root, "out")

    def tearDown(self):
        self.sb.close()

    def test_convert(self):
        written, stats = ls.convert_sources(SOURCES, self.out, self.sb.lib,
                                            {"ABC21", "XY20"})
        rel = sorted(os.path.relpath(p, self.out).replace("\\", "/") for p in written)
        self.assertIn("cards/ABC21/lemma-2-1.md", rel)
        self.assertIn("cards/ABC21/theorem-3-4.md", rel)
        self.assertIn("cards/ABC21/entry.md", rel)
        self.assertIn("cards/ABC21/lemma-2-1-again.md", rel)     # the ABC21 prefix taken
        self.assertIn("cards/XY20/later-re-check-2026-09-24.md", rel)  # moved by evidence
        self.assertTrue(any(r.startswith("cards/_unkeyed/") for r in rel))
        self.assertTrue(os.path.isfile(os.path.join(self.out, "cards", "ABC21", "_intro.md")))
        self.assertEqual(stats["cards"], 6)
        self.assertEqual(stats["unkeyed_blocks"],
                         ["Somebody, arXiv:1710.05505 (not in references.bib)"])

        meta, body = cards.read_card(os.path.join(self.out, "cards", "ABC21",
                                                  "lemma-2-1.md"))
        self.assertEqual(meta["read_from"], "source")
        self.assertEqual(meta["verdict"], "match")
        self.assertEqual(meta["used_by"], ["paper:defn:y", "paper:lem:x"])
        self.assertEqual(meta["source_label"], "L:one")
        self.assertEqual(meta["checked"], "2026-09-19")
        self.assertEqual(meta["version"], "arXiv v2 (1 Jan 2021)")   # from the index row
        self.assertTrue(meta["migrated"])
        errs, warns, q = cards.validate_card(meta, body, self.sb.lib)
        self.assertEqual(errs, [])
        self.assertEqual(q["status"], "verified")
        self.assertIn("## Ledger text", body)

        meta, _ = cards.read_card(os.path.join(self.out, "cards", "ABC21",
                                               "theorem-3-4.md"))
        self.assertEqual((meta["read_from"], meta["verdict"]), ("extraction", "mismatch"))

    def test_related(self):
        written = ls.convert_related(RELATED, self.out)
        names = sorted(os.path.basename(p) for p in written)
        self.assertEqual(names, ["2026-09-19-lem-x-sections-a-tex.md",
                                 "2026-09-20-second-block.md", "_header.md"])
        with open(written[1], encoding="utf-8") as fh:
            self.assertIn("### Queries run", fh.read())

    def test_refuses_to_write_into_a_home(self):
        src = self.sb.write("s.md", SOURCES)
        code, out, err = fixtures.run_script(
            "ledger_split.py", None, ["--sources", src, "--out",
                                      os.path.join(self.sb.lib, "x")])
        self.assertEqual(code, 2)
        self.assertIn("home of expert@main", err)
        code, out, err = fixtures.run_script(
            "ledger_split.py", None, ["--sources", src, "--out", self.out, "--library",
                                      self.sb.lib])
        self.assertEqual(code, 0, err)
        with open(os.path.join(self.out, "stats.json"), encoding="utf-8") as fh:
            st = json.load(fh)
        self.assertEqual(st["cards"], 6)
        self.assertEqual(len(st["cards_in_order"]), 6)


